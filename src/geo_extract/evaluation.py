"""Score an extractor against labeled cases."""

from __future__ import annotations

import json
from collections.abc import Iterable
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from .base import Extractor
from .models import Candidate


@dataclass
class CaseScore:
    id: str
    tp: int
    fp: int
    fn: int
    pos_checked: int
    pos_correct: int
    target_correct: bool
    target_pos_correct: bool | None
    errors: list[str] = field(default_factory=list)


@dataclass
class Report:
    extractor: str
    split: str
    cases: list[CaseScore]

    def _sum(self, attr: str) -> int:
        return sum(int(getattr(c, attr)) for c in self.cases)

    @property
    def precision(self) -> float:
        tp, fp = self._sum("tp"), self._sum("fp")
        return tp / (tp + fp) if tp + fp else 1.0

    @property
    def recall(self) -> float:
        tp, fn = self._sum("tp"), self._sum("fn")
        return tp / (tp + fn) if tp + fn else 1.0

    @property
    def f1(self) -> float:
        p, r = self.precision, self.recall
        return 2 * p * r / (p + r) if p + r else 0.0

    @property
    def position_accuracy(self) -> float:
        checked = self._sum("pos_checked")
        return self._sum("pos_correct") / checked if checked else 1.0

    @property
    def target_accuracy(self) -> float:
        return sum(c.target_correct for c in self.cases) / len(self.cases) if self.cases else 1.0

    @property
    def exact_cases(self) -> int:
        return sum(1 for c in self.cases if not c.errors)

    def summary(self) -> dict[str, Any]:
        return {
            "extractor": self.extractor,
            "split": self.split,
            "cases": len(self.cases),
            "precision": round(self.precision, 3),
            "recall": round(self.recall, 3),
            "f1": round(self.f1, 3),
            "position_accuracy": round(self.position_accuracy, 3),
            "target_accuracy": round(self.target_accuracy, 3),
            "exact_cases": self.exact_cases,
        }


def load_cases(path: str | Path) -> list[dict[str, Any]]:
    with open(path, encoding="utf8") as f:
        return [json.loads(line) for line in f if line.strip()]


def score_case(extractor: Extractor, case: dict[str, Any]) -> CaseScore:
    cands = [Candidate.from_obj(c) for c in case["candidates"]]
    result = extractor.extract(case["answer"], cands, case["target"], case.get("location"))
    pred = result.named_candidates
    gold = {g["candidate"]: g["position"] for g in case["gold"]["named"]}
    errors: list[str] = []
    tp = len(pred.keys() & gold.keys())
    fp_names = sorted(pred.keys() - gold.keys())
    fn_names = sorted(gold.keys() - pred.keys())
    errors += [f"false positive: {n}" for n in fp_names]
    errors += [f"missed: {n}" for n in fn_names]
    checked = correct = 0
    for name in pred.keys() & gold.keys():
        checked += 1
        if pred[name] == gold[name]:
            correct += 1
        else:
            errors.append(f"position {name}: got {pred[name]}, want {gold[name]}")
    target_correct = result.target_named == case["gold"]["target_named"]
    target_pos: bool | None = None
    if case["gold"]["target_named"] and result.target_named:
        target_pos = result.target_position == case["gold"]["target_position"]
    return CaseScore(
        case["id"],
        tp,
        len(fp_names),
        len(fn_names),
        checked,
        correct,
        target_correct,
        target_pos,
        errors,
    )


def evaluate(extractor: Extractor, cases: Iterable[dict[str, Any]], split: str) -> Report:
    return Report(extractor.name, split, [score_case(extractor, c) for c in cases])


def to_markdown(reports: list[Report]) -> str:
    lines = [
        "# Eval results",
        "",
        "Generated by `geo-extract eval`. The dataset is synthetic (see `evals/README.md`).",
        "",
        "| Extractor | Split | Cases | Precision | Recall | F1 | Position acc. | Target acc. "
        "| Cases fully right |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in reports:
        s = r.summary()
        lines.append(
            f"| {s['extractor']} | {s['split']} | {s['cases']} | {s['precision']:.3f} | "
            f"{s['recall']:.3f} | {s['f1']:.3f} | {s['position_accuracy']:.3f} | "
            f"{s['target_accuracy']:.3f} | {s['exact_cases']}/{s['cases']} |"
        )
    for r in reports:
        misses = [c for c in r.cases if c.errors]
        lines += ["", f"## {r.extractor} / {r.split}: cases with errors ({len(misses)})", ""]
        if not misses:
            lines.append("None.")
        for c in misses:
            lines.append(f"- **{c.id}**: " + "; ".join(c.errors))
    return "\n".join(lines) + "\n"
